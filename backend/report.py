import json
from pathlib import Path

TABLE_LIMIT = 160


def _cell(text, limit=TABLE_LIMIT):
    value = " ".join(str(text).split()).replace("|", "/")
    if len(value) > limit:
        return value[:limit] + "..."
    return value


def _plan_section(plan):
    lines = ["## what was planned", ""]
    if not plan["checks"]:
        lines.append("no checks were planned for this run")
        return lines
    lines += ["| check | why the agent picked it |", "|---|---|"]
    for item in plan["checks"]:
        lines.append(f"| `{item['id']}` | {_cell(item['reason'])} |")
    if plan.get("skipped"):
        lines += ["", "skipped: " + ", ".join(f"`{item['id']}` ({item['reason']})" for item in plan["skipped"])]
    return lines


def _results_section(results):
    lines = ["## results", "", "| check | severity | result | detail | evidence |", "|---|---|---|---|---|"]
    for row in results:
        evidence = f"[{row['evidence_path']}]({row['evidence_path']})" if row["evidence_path"] else ""
        lines.append(
            f"| `{row['check_id']}` | {row['severity']} | {row['result']} | {_cell(row['detail'])} | {evidence} |"
        )
    return lines


def _findings_section(findings):
    if not findings:
        return ["## findings", "", "no confirmed findings in this run."]
    lines = ["## findings"]
    for index, finding in enumerate(findings, start=1):
        lines += ["", f"### {index}. {finding['title']} ({finding['severity']}, {finding['status']})", ""]
        lines.append(f"- check: `{finding['check_id']}`")
        lines.append(f"- evidence: `{finding['evidence_path']}`")
        lines.append(f"- recorded by the runner: {_cell(finding['description'], 400)}")
        if finding["impact"]:
            source = "model written" if finding["model_generated"] else "catalogue fallback"
            lines.append(f"- impact ({source}): {_cell(finding['impact'], 400)}")
        if finding["remediation"]:
            source = "model written" if finding["model_generated"] else "catalogue fallback"
            lines.append(f"- remediation ({source}): {_cell(finding['remediation'], 400)}")
    return lines


def _untested_section(results, plan):
    lines = ["## not tested or inconclusive", ""]
    notes = []
    for row in results:
        if row["result"] == "error":
            notes.append(f"`{row['check_id']}` could not run: {_cell(row['detail'], 200)}")
        elif row["result"] == "not_applicable":
            notes.append(f"`{row['check_id']}` did not apply: {_cell(row['detail'], 200)}")
    for item in plan.get("skipped", []):
        notes.append(f"`{item['id']}` was not run: {item['reason']}")
    if not notes:
        lines.append("every planned check produced a result.")
        return lines
    lines += [f"- {note}" for note in notes]
    return lines


def render_report(run, plan, results, findings):
    lines = [
        f"# black-box test report, run {run['id']}",
        "",
        f"- target: {run['target']}",
        f"- status: {run['status']}",
        f"- started: {run['started_at']}",
        f"- finished: {run['finished_at'] or 'still running'}",
        f"- agent: {run['model']}",
        f"- check plan from: {plan['source']}",
        f"- requests used: {run['request_count']}",
    ]
    if run["notes"]:
        lines.append(f"- notes: {run['notes']}")
    if run["error"]:
        lines.append(f"- error: {run['error']}")

    lines += ["", "## summary", ""]
    if run["summary"]:
        lines.append(run["summary"])
    else:
        lines.append("no summary was written for this run")
    if run["summary_source"] == "model":
        note = ("the summary paragraph above was written by the model. the results, the severities and the findings "
                "below are recorded by the runner from the actual responses.")
    else:
        note = ("the summary paragraph above was written by the runner, not by the model. the results, the severities "
                "and the findings below are recorded from the actual responses.")
    lines += ["", note, "", "every finding points at the evidence file it came from.", ""]

    lines += _plan_section(plan)
    lines += [""] + _results_section(results)
    lines += [""] + _findings_section(findings)
    lines += [""] + _untested_section(results, plan)
    lines += [
        "",
        "---",
        "",
        "generated by the deepseek black-box security lab. checks were limited to the target above, "
        "which had to match ALLOWED_TARGETS before the run started.",
        "",
    ]
    return "\n".join(lines)


def write_report(run, plan, results, findings, cfg):
    text = render_report(run, plan, results, findings)
    reports_dir = Path(cfg["reports_dir"])
    reports_dir.mkdir(parents=True, exist_ok=True)
    path = reports_dir / f"run_{run['id']}.md"
    path.write_text(text, encoding="utf-8")
    return path, text


def parse_plan(run):
    # a run that fails before planning never gets a plan written, so this has to cope with
    # the column default and with anything else that is not a plan dict
    try:
        plan = json.loads(run["planned_json"])
    except (TypeError, ValueError):
        plan = None
    if not isinstance(plan, dict):
        return {"source": "none", "checks": [], "skipped": []}
    return {
        "source": plan.get("source", "none"),
        "checks": plan.get("checks", []),
        "skipped": plan.get("skipped", []),
    }
